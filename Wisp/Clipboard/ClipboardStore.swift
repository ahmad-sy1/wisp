import AppKit

/// One copied text.
struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case url, code, text }

    var id = UUID()
    let text: String
    let kind: Kind
    var copiedAt: Date
}

/// The last 20 texts you copied (board 5), kept on this Mac only.
///
/// macOS has no notification for the pasteboard, so wisp looks at its change count once
/// a second: reading one integer, with a generous timer tolerance so the system can
/// bundle the wake-ups. Nothing else runs; the history can be switched off in Settings,
/// and then nothing runs at all.
///
/// Never kept: anything marked concealed or transient (password managers, one-time
/// codes), and anything copied while a password manager is in front.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    static let limit = 20

    @Published private(set) var items: [ClipboardItem] = []
    /// The search field in the tab bar.
    @Published var query = ""
    @Published var isEnabled: Bool {
        didSet {
            defaults.set(isEnabled, forKey: Key.enabled)
            isEnabled ? start() : stop()
        }
    }

    private let pasteboard = NSPasteboard.general
    private let defaults = UserDefaults.standard
    private var timer: Timer?
    private var lastChange = 0

    private enum Key { static let enabled = "clipboardEnabled" }

    /// nspasteboard.org markers: password managers and generated codes set these.
    private static let skipTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private static let passwordManagers: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.Passwords", "com.apple.keychainaccess",
        "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "org.keepassxc.keepassxc",
    ]

    private static var file: URL {
        FileManager.default.homeDirectoryForCurrentUser
            .appendingPathComponent("Library/Application Support/wisp/clipboard.json")
    }

    private init() {
        isEnabled = defaults.object(forKey: Key.enabled) as? Bool ?? true
        items = Self.load()
    }

    func start() {
        guard isEnabled, timer == nil else { return }
        lastChange = pasteboard.changeCount
        let timer = Timer(timeInterval: 1, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardStore.shared.check() }
        }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Puts an item back on the pasteboard and at the top of the list.
    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChange = pasteboard.changeCount
        add(item.text, kind: item.kind)
    }

    var visibleItems: [ClipboardItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        return q.isEmpty ? items : items.filter { $0.text.localizedCaseInsensitiveContains(q) }
    }

    func clear() {
        items = []
        save()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    private func check() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skipTypes) else { return }
        let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? ""
        guard !Self.passwordManagers.contains(front) else { return }
        guard let text = pasteboard.string(forType: .string) else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        add(String(trimmed.prefix(20_000)), kind: Self.kind(of: trimmed, from: front))
    }

    private func add(_ text: String, kind: ClipboardItem.Kind) {
        items.removeAll { $0.text == text }
        items.insert(ClipboardItem(text: text, kind: kind, copiedAt: .now), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
        save()
    }

    // MARK: - Kind

    static func kind(of text: String, from bundle: String) -> ClipboardItem.Kind {
        if !text.contains(where: \.isWhitespace), let url = URL(string: text),
           let scheme = url.scheme?.lowercased(), ["http", "https", "ftp", "file", "mailto"].contains(scheme) {
            return .url
        }
        let codeApps = ["com.jetbrains.", "com.microsoft.vscode", "com.apple.dt.xcode", "com.apple.terminal",
                        "com.googlecode.iterm2", "dev.warp.", "com.mitchellh.ghostty", "dev.zed."]
        if codeApps.contains(where: { bundle.lowercased().hasPrefix($0) }) { return .code }
        let marks = [";", "{", "}", "=>", "->", "()", "==", "</", "import ", "func ", "const ", "let ", "def ", "#include"]
        let hits = marks.filter { text.contains($0) }.count
        return hits >= 2 ? .code : .text
    }

    // MARK: - Storage

    private static func load() -> [ClipboardItem] {
        guard let data = try? Data(contentsOf: file) else { return [] }
        return (try? JSONDecoder().decode([ClipboardItem].self, from: data)) ?? []
    }

    private func save() {
        let file = Self.file
        try? FileManager.default.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
        guard let data = try? JSONEncoder().encode(items) else { return }
        // Only you can read it: copied text can be personal.
        FileManager.default.createFile(atPath: file.path, contents: data, attributes: [.posixPermissions: 0o600])
    }
}
